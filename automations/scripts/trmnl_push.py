#!/usr/bin/env python3
"""
TRMNL payload transport: the BUILDERS registry, the webhook push, and the pulse
builders the home page data reads.

    python3 automations/scripts/trmnl_push.py <plugin> [--dry-run] [--local] [--out PATH] [--force]

    <plugin>    Folder name under trmnl/ (e.g. pfc-today). Must have a builder
                registered in BUILDERS below.
    --dry-run   Print the payload and its byte size. No network call.
    --local     Write the payload into trmnl/<plugin>/.trmnlp.yml under the
                generated marker so `trmnlp serve` previews against real data.
                No network call.
    --out PATH  Write the payload as bare JSON to PATH (the polling transport's
                shape). No network call.
    --force     Skip the local rate-limit guard.

Each screen mirrors one band of the web home page; its builder lives in
`trmnl_home.py` and reads `home_data.build_home`, the same call the page makes.
Both transports read the BUILDERS registry here: `trmnl_serve.py` calls a builder
per HTTP request (polling, the default), and a bare invocation here POSTs the
result as a webhook body.

Webhook UUID comes from .env as TRMNL_WEBHOOK_<PLUGIN_SLUG_UPPER> — the plugin
folder `pfc-today` reads TRMNL_WEBHOOK_PFC_TODAY.

Why the guards: TRMNL rate-limits webhook pushes to 12 requests/hour at 2 KB per
request on a standard account (30/hour at 5 KB on TRMNL+). Blowing the limit
returns 429 and the screen goes stale, so this script refuses to push more often
than MIN_PUSH_INTERVAL_SECONDS and refuses to send an oversized payload at all.
See docs/trmnl-plugins.md.
"""

import argparse
import datetime as dt
import json
import os
import sys
import urllib.error
import urllib.request
from pathlib import Path
from zoneinfo import ZoneInfo

SCRIPT_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPT_DIR))

REPO_ROOT = SCRIPT_DIR.parents[1]
TRMNL_DIR = REPO_ROOT / "trmnl"

WEBHOOK_BASE = "https://trmnl.com/api/custom_plugins"
TIMEOUT_SECONDS = 15

# Standard account: 12 req/hr. One push per 5 minutes stays well inside it.
MIN_PUSH_INTERVAL_SECONDS = 300
DEFAULT_PAYLOAD_LIMIT_BYTES = 2048

GENERATED_MARKER = "# --- generated by trmnl_push.py --local (do not hand-edit below) ---"

# ── Tune these to your own system ────────────────────────────────────────────
# The habit id that counts as "did the thing that makes a good day" — the
# exercise / movement habit from config/habit_schema.yaml. Body first (the
# pfc-pulse screen and the web band) shows whether it is done today.
EXERCISE_HABIT_ID = "morning-walk"
EXERCISE_LABEL = "Morning walk"



# ── env ───────────────────────────────────────────────────────────────────────


def load_env():
    """Load .env into a dict, then let real environment variables win."""
    env = {}
    env_path = REPO_ROOT / ".env"
    if env_path.exists():
        for line in env_path.read_text().splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            v = v.strip()
            # Values may be quoted so bash `source` survives shell metacharacters
            # (an unquoted & in a value would otherwise break the bin/ scripts).
            env[k.strip()] = v[1:-1] if len(v) >= 2 and v[0] == v[-1] and v[0] in "'\"" else v
    env.update({k: v for k, v in os.environ.items() if v})
    return env


def today_local(env) -> str:
    tz = ZoneInfo(env.get("LOCAL_TZ", "America/Denver"))
    return dt.datetime.now(tz).strftime("%Y-%m-%d")


# ── repo readers ──────────────────────────────────────────────────────────────


def read_ndjson(rel_path):
    p = REPO_ROOT / rel_path
    if not p.exists():
        return []
    out = []
    for line in p.read_text().splitlines():
        line = line.strip()
        if line:
            out.append(json.loads(line))
    return out


def clip(text, limit):
    text = (text or "").strip()
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def _exercise_days():
    """Dates the exercise habit was done, from either source that records it:
    a completed habit log, or `morning_movement: true` on a day-tracking row."""
    dates = {r["date"] for r in read_ndjson("7-habits/_data/habits-daily.ndjson")
             if r.get("habit_id") == EXERCISE_HABIT_ID and r.get("completed") and r.get("date")}
    dates |= {r["date"] for r in read_ndjson("data/day-tracking.ndjson")
              if r.get("morning_movement") and r.get("date")}
    return dates


def _ascii(text):
    """Targets carry ≥ / ≤ glyphs and fix strings carry em dashes; e-ink renders
    those unreliably (same class of failure as emoji). Transliterate rather than
    dropping the comparison."""
    return ((text or "").replace("≥", ">=").replace("≤", "<=")
            .replace("—", "-").replace("–", "-").replace("×", "x")
            .replace("→", "->").replace("·", "-"))


# E-ink status marks — screens have no emoji font, so a status becomes the
# colour spelled out in caps. Punctuation marks ([!] / [~] / [ ]) need a legend,
# and a legend that isn't printed on the screen is a legend the viewer doesn't
# have. A word is its own legend. ONE vocabulary across every screen —
# see AGENTS.md § "Metrics point one direction". STATUS_WORD is keyed by colour
# name, EINK_MARK by the pulse machinery's emoji; they must never diverge.
STATUS_WORD = {"green": "GREEN", "yellow": "YELLOW", "red": "RED"}
EINK_MARK = {"🟢": STATUS_WORD["green"], "🟡": STATUS_WORD["yellow"],
             "🔴": STATUS_WORD["red"], "⚪": "NO DATA"}


# ── pulse builders ────────────────────────────────────────────────────────────
#
# Not screens of their own: home_data._pulse reads both (last night's levers, plus
# each lever's nights on target over 30 days), and the pfc-pulse screen shows them
# through trmnl_home.body_payload.


def build_pfc_pulse(env, today):
    """Last night's levers vs target, the verdict, and tonight's one move.

    Thresholds, verdict, and move all come from pulse.pulse_snapshot — if tiering
    or targets change, they change there (or in `health.pulse` in
    config/automation_config.yaml), in one place.
    """
    from pulse import pulse_snapshot

    snap = pulse_snapshot(read_ndjson("data/day-tracking.ndjson"))
    exercised = today in _exercise_days()
    if snap is None:
        return {"date": today, "levers": [], "verdict_mark": "NO DATA",
                "verdict": "No day-tracking data yet.", "move": "",
                "exercise_label": EXERCISE_LABEL, "exercise_done": exercised,
                "exercise_text": "done" if exercised else "not yet"}

    status_rank = {"🔴": 0, "🟡": 1, "🟢": 2, "⚪": 3}
    # _ascii on value/target: they carry >= / <= glyphs that e-ink renders
    # unreliably — the same treatment build_pfc_pulse_trend gives them.
    # Red first, then yellow, then green — worst at the top so the thing to fix
    # is the thing you read first. Tier only breaks ties within a colour.
    levers = [
        {"label": label, "value": _ascii(disp), "target": _ascii(target), "tier": tier,
         "mark": EINK_MARK[status]}
        for (lid, tier, rank, label, disp, target, status)
        in sorted(snap["levers"], key=lambda lv: (status_rank[lv[6]], lv[2]))
    ]
    return {
        "date": snap["date"],
        "levers": levers,
        "verdict_mark": EINK_MARK[snap["verdict"]["status"]],
        "verdict": _ascii(snap["verdict"]["text"]),
        "move": clip(_ascii(snap["move"]), 140),
        # Today's action, independent of `snap` — which may still show last
        # night's sleep during the pre-noon gap.
        "exercise_label": EXERCISE_LABEL,
        "exercise_done": exercised,
        "exercise_text": "done" if exercised else "not yet",
    }


# Window rollups spell the colour out — same one-vocabulary rule as EINK_MARK.
WINDOW_STATUS_WORD = {"\U0001F7E2": "GREEN", "\U0001F7E1": "YELLOW",
                      "\U0001F534": "RED", "⚪": "NO DATA"}


def build_pfc_pulse_trend(env, today):
    """The pulse over 30 days: per-lever days-on-target + the standing fix.

    build_pfc_pulse answers tonight; this answers lately. Thresholds, history, and
    remediation all come from pulse.py — one home for the pulse rules.
    Every count on this screen is GOOD days out of the window, so high is
    always good: an on-count headline over off-count rows meant every number
    had to be re-read for direction (AGENTS.md § "Metrics point one direction").
    Counts rather than a grid of status glyphs: a handful of ranked rows are
    legible across a room, 200-plus status marks are not.
    """
    from pulse import (VERDICT_MIN_CRITICAL_GREEN, chronic_misses, pulse_history,
                       pulse_levers, pulse_window_status)

    rows = read_ndjson("data/day-tracking.ndjson")
    hist = pulse_history(rows, 30)
    if hist is None:
        return {"window": 30, "from": "", "to": "", "levers": [], "chronic": None,
                "green_days": 0}

    n = len(hist["dates"])
    levers = []
    for lid in hist["order"]:
        s = hist["series"][lid]
        # `on` counts green days only; a day with no reading is neither on nor
        # off, so on + off can be < n.
        on = sum(1 for x in s["statuses"] if x == "🟢")
        levers.append({"id": lid, "label": s["label"], "on": on, "n": n,
                       "status": WINDOW_STATUS_WORD[pulse_window_status(s["statuses"])],
                       # target_plain, not target: the latter appends last night's
                       # distance-to-next-tier, which says nothing about a 30-day
                       # window and reads as if it did.
                       "target": _ascii(s.get("target_plain") or s["target"]),
                       "tier": s["tier"], "last": _ascii(s["last_disp"])})
    levers.sort(key=lambda lv: (lv["on"], lv["label"]))

    # Chronic = off on at least half the window, the same definition every other
    # pulse surface uses. Detected on off-days, reported as on-days so the
    # screen never mixes directions.
    worst = chronic_misses(hist, max_items=1)
    chronic = None
    if worst:
        off, lid, series, fix = worst[0]
        on = sum(1 for x in series["statuses"] if x == "🟢")
        chronic = {"label": series["label"], "on": on, "n": n,
                   "status": WINDOW_STATUS_WORD[pulse_window_status(series["statuses"])],
                   "fix": clip(_ascii(fix), 180)}

    # green_days: how often the setup for a great day was actually in place —
    # the same bar pulse_snapshot's verdict uses.
    by_date = {r["date"]: r for r in rows if r.get("date")}
    green_days = 0
    for d in hist["dates"]:
        lv = pulse_levers(by_date[d])
        status = {x[0]: x[6] for x in lv}
        crit_green = sum(1 for x in lv if x[1] == "CRITICAL" and x[6] == "🟢")
        if crit_green >= VERDICT_MIN_CRITICAL_GREEN and status.get("debt") != "🔴":
            green_days += 1

    return {"window": 30, "from": hist["dates"][0], "to": hist["dates"][-1],
            "levers": levers, "chronic": chronic, "green_days": green_days}


# One screen per band of the web home page, in the page's order. The band builders live
# in trmnl_home.py and read home_data.build_home, the same call the page makes.
import trmnl_home  # noqa: E402

BUILDERS = {
    "pfc-pulse": trmnl_home.build_pfc_body,
    "pfc-today": trmnl_home.build_pfc_today,
    "pfc-habits": trmnl_home.build_pfc_habits,
    "pfc-week": trmnl_home.build_pfc_week,
    "pfc-focus": trmnl_home.build_pfc_focus,
    "pfc-projects": trmnl_home.build_pfc_projects,
    "pfc-trends": trmnl_home.build_pfc_trends,
    "pfc-areas": trmnl_home.build_pfc_areas,
    "pfc-values": trmnl_home.build_pfc_values,
    "pfc-visions": trmnl_home.build_pfc_visions,
    "pfc-front-of-mind": trmnl_home.build_pfc_front_of_mind,
}


# ── push ──────────────────────────────────────────────────────────────────────


def env_key(plugin):
    return "TRMNL_WEBHOOK_" + plugin.replace("-", "_").upper()


def stamp_path(plugin):
    return REPO_ROOT / "data" / f".trmnl-last-push-{plugin}"


def rate_limited(plugin):
    """Return seconds still to wait, or 0 when a push is allowed."""
    p = stamp_path(plugin)
    if not p.exists():
        return 0
    elapsed = dt.datetime.now().timestamp() - p.stat().st_mtime
    remaining = MIN_PUSH_INTERVAL_SECONDS - elapsed
    return int(remaining) if remaining > 0 else 0


def post_payload(uuid, payload):
    body = json.dumps({"merge_variables": payload}).encode()
    req = urllib.request.Request(
        f"{WEBHOOK_BASE}/{uuid}",
        data=body,
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(req, timeout=TIMEOUT_SECONDS) as resp:
        return resp.status, resp.read().decode()


def write_local_fixture(plugin, payload):
    """Rewrite the generated block of trmnl/<plugin>/.trmnlp.yml with the payload.

    JSON is valid YAML, so the payload is emitted as a flow mapping — no YAML
    library needed. Everything above the marker is preserved verbatim.
    """
    path = TRMNL_DIR / plugin / ".trmnlp.yml"
    if not path.exists():
        raise SystemExit(f"No .trmnlp.yml at {path}")
    head = path.read_text().split(GENERATED_MARKER)[0].rstrip() + "\n"
    block = json.dumps(payload, indent=2)
    path.write_text(f"{head}\n{GENERATED_MARKER}\nvariables:\n  " + block.replace("\n", "\n  ") + "\n")
    return path


def main(argv):
    parser = argparse.ArgumentParser(description="Build and push a TRMNL plugin payload.")
    parser.add_argument("plugin", help="plugin folder name under trmnl/")
    parser.add_argument("--dry-run", action="store_true", help="print the payload, do not send")
    parser.add_argument("--local", action="store_true", help="write the payload into .trmnlp.yml for trmnlp serve")
    parser.add_argument("--out", metavar="PATH", help="write the payload JSON to PATH (the polling shape); no network call")
    parser.add_argument("--force", action="store_true", help="skip the rate-limit guard")
    args = parser.parse_args(argv)

    builder = BUILDERS.get(args.plugin)
    if builder is None:
        print(
            f"No payload builder registered for '{args.plugin}'. "
            f"Known: {', '.join(sorted(BUILDERS))}. Add one in {Path(__file__).name}.",
            file=sys.stderr,
        )
        return 1

    env = load_env()
    payload = builder(env, today_local(env))
    encoded = json.dumps({"merge_variables": payload})
    size = len(encoded.encode())
    limit = int(env.get("TRMNL_PAYLOAD_LIMIT", DEFAULT_PAYLOAD_LIMIT_BYTES))

    if args.out:
        # Polling transport: TRMNL fetches this file, so it is served bare
        # rather than wrapped in {"merge_variables": ...} the way a webhook
        # body is.
        out = Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(payload, indent=2) + "\n")
        print(f"wrote {out} ({len(json.dumps(payload).encode())} bytes)", file=sys.stderr)
        return 0

    if args.dry_run or args.local:
        print(json.dumps(payload, indent=2))
        print(f"\npayload: {size} bytes (limit {limit})", file=sys.stderr)
        if size > limit:
            print("OVER LIMIT — trim the builder before pushing.", file=sys.stderr)
        if args.local:
            print(f"wrote {write_local_fixture(args.plugin, payload)}", file=sys.stderr)
        return 0

    if size > limit:
        print(
            f"Payload is {size} bytes, over the {limit}-byte TRMNL webhook limit. "
            f"Trim the builder for '{args.plugin}' — do not raise the limit unless the "
            f"account is on TRMNL+ (5 KB).",
            file=sys.stderr,
        )
        return 1

    uuid = env.get(env_key(args.plugin))
    if not uuid:
        print(
            f"Missing {env_key(args.plugin)} in .env — copy the plugin's webhook UUID "
            f"from its TRMNL settings page. See .env.example.",
            file=sys.stderr,
        )
        return 1

    wait = 0 if args.force else rate_limited(args.plugin)
    if wait:
        print(
            f"Last push was under {MIN_PUSH_INTERVAL_SECONDS}s ago; {wait}s to go. "
            f"TRMNL allows 12 pushes/hour. Re-run with --force to override.",
            file=sys.stderr,
        )
        return 1

    try:
        status, body = post_payload(uuid, payload)
    except urllib.error.HTTPError as e:
        detail = e.read().decode(errors="replace")[:300]
        print(f"TRMNL returned HTTP {e.code}: {detail}", file=sys.stderr)
        return 1
    except urllib.error.URLError as e:
        print(f"Could not reach TRMNL: {e.reason}", file=sys.stderr)
        return 1

    stamp_path(args.plugin).write_text(dt.datetime.now().isoformat())
    print(f"pushed {args.plugin}: HTTP {status} ({size} bytes) {body[:200]}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
