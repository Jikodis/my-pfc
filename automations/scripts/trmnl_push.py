def build_pfc_today(env, today):
    """The 2+1, daily habit status, and the latest day rating for the focus day.

    The focus day is tomorrow once tomorrow's 2+1 has been staged (the evening
    check-in does this), otherwise today. That way the screen flips to the next
    day's plan at the check-in instead of sitting on the day just closed —
    which is what you want on the wall overnight and at breakfast.
    """
    tasks = {t["id"]: t for t in read_ndjson("6-tasks/_data/tasks.ndjson")}
    archive = {t["id"]: t for t in read_ndjson("6-tasks/_data/tasks-archive.ndjson")}
    tasks.update({k: v for k, v in archive.items() if k not in tasks})

    tomorrow = (dt.date.fromisoformat(today) + dt.timedelta(days=1)).isoformat()
    focus_records = read_ndjson("6-tasks/_data/daily-focus.ndjson")

    def record_for(date):
        return next((f for f in reversed(focus_records) if f.get("date") == date), None)

    focus = record_for(tomorrow)
    focus_date = tomorrow
    if focus is None:
        focus = record_for(today)
        focus_date = today

    def task_entry(task_id, done):
        task = tasks.get(task_id)
        return {
            "title": clip(task["description"] if task else task_id, 60),
            "done": done,
        }

    critical = []
    bonus = None
    if focus:
        completed = set(focus.get("completed") or [])
        critical = [task_entry(tid, tid in completed) for tid in focus.get("critical") or []]
        if focus.get("bonus"):
            bonus = task_entry(focus["bonus"], bool(focus.get("bonus_completed")))

    days = read_ndjson("data/day-tracking.ndjson")
    rated = [d for d in days if d.get("rating") is not None]
    last_rating = rated[-1] if rated else None

    # Habits are always TODAY's state (they reset at midnight), even when the
    # 2+1 column has already flipped to tomorrow's staged plan.
    logs = read_ndjson("7-habits/_data/habits-daily.ndjson")
    done_today = {h["habit_id"] for h in logs if h.get("date") == today and h.get("completed")}
    habits = [{"title": _habit_title(h["id"]), "done": h["id"] in done_today}
              for h in daily_habits()]

    return {
        "date": focus_date,
        "weekday": dt.date.fromisoformat(focus_date).strftime("%A"),
        "critical": critical,
        "bonus": bonus,
        "habits": habits,
        "habits_done": sum(1 for h in habits if h["done"]),
        "habits_total": len(habits),
        "last_rating": (last_rating or {}).get("rating"),
        "last_rating_date": (last_rating or {}).get("date"),
    }


def build_pfc_habits(env, today):
    """Daily habits with today's state + 7-day counts; monthly habits vs target."""
    week_start = (dt.date.fromisoformat(today) - dt.timedelta(days=6)).isoformat()
    logs = read_ndjson("7-habits/_data/habits-daily.ndjson")
    done_today = {h["habit_id"] for h in logs if h.get("date") == today and h.get("completed")}
    week_counts = {}
    for h in logs:
        if h.get("completed") and week_start <= (h.get("date") or "") <= today:
            week_counts[h["habit_id"]] = week_counts.get(h["habit_id"], 0) + 1

    # Denominator is the habit's LIVE ramped frequency, not a flat 7. A habit
    # ramped down to 1/wk showing "0/7" reads as six misses when the bar is one.
    daily = [
        {"title": _habit_title(h["id"]), "done": h["id"] in done_today,
         "week": f"{week_counts.get(h['id'], 0)}/{h.get('frequency', 7)}"}
        for h in daily_habits()
    ]

    month = today[:7]
    mlogs = read_ndjson("7-habits/_data/habits-monthly.ndjson")
    monthly = []
    today_date = dt.date.fromisoformat(today)
    days_in_month = (today_date.replace(day=28) + dt.timedelta(days=4)).replace(day=1) - dt.timedelta(days=1)
    month_frac = today_date.day / days_in_month.day
    for h in monthly_habits():
        count = sum(1 for r in mlogs
                    if r.get("habit_id") == h["id"] and r.get("completed")
                    and (r.get("date") or "").startswith(month))
        target = h.get("frequency") or 1
        met = count >= target
        pace = "done" if met else ("on pace" if count >= target * month_frac else "behind")
        monthly.append({"title": _habit_title(h["id"]), "count": count,
                        "target": target, "met": met, "pace": pace})

    return {
        "daily": daily,
        "daily_done": sum(1 for h in daily if h["done"]),
        "daily_total": len(daily),
        "monthly": monthly,
        "month_label": today_date.strftime("%B"),
    }


def build_pfc_pulse(env, today):
    """Daily Pulse: levers vs target, the verdict, and tonight's one move.

    Thresholds, verdict, and move all come from pulse.pulse_snapshot — if tiering
    or targets change, they change there (or in `health.pulse` in
    config/automation_config.yaml), in one place.
    """
    from pulse import pulse_snapshot

    snap = pulse_snapshot(read_ndjson("data/day-tracking.ndjson"))
    exercised = today in _exercise_days()
    if snap is None:
        return {"date": today, "levers": [], "verdict_mark": "NO DATA",
                "verdict": "No day-tracking data yet.", "move": "",
                "exercise_label": EXERCISE_LABEL, "exercise_done": exercised,
                "exercise_text": "done" if exercised else "not yet"}

    status_rank = {"🔴": 0, "🟡": 1, "🟢": 2, "⚪": 3}
    # _ascii on value/target: they carry >= / <= glyphs that e-ink renders
    # unreliably — the same treatment build_pfc_pulse_trend gives them.
    # Red first, then yellow, then green — worst at the top so the thing to fix
    # is the thing you read first. Tier only breaks ties within a colour.
    levers = [
        {"label": label, "value": _ascii(disp), "target": _ascii(target), "tier": tier,
         "mark": EINK_MARK[status]}
        for (lid, tier, rank, label, disp, target, status)
        in sorted(snap["levers"], key=lambda lv: (status_rank[lv[6]], lv[2]))
    ]
    return {
        "date": snap["date"],
        "levers": levers,
        "verdict_mark": EINK_MARK[snap["verdict"]["status"]],
        "verdict": _ascii(snap["verdict"]["text"]),
        "move": clip(_ascii(snap["move"]), 140),
        # Today's action, independent of `snap` — which may still show last
        # night's sleep during the pre-noon gap.
        "exercise_label": EXERCISE_LABEL,
        "exercise_done": exercised,
        "exercise_text": "done" if exercised else "not yet",
    }


# Window rollups spell the colour out — same one-vocabulary rule as EINK_MARK.
WINDOW_STATUS_WORD = {"\U0001F7E2": "GREEN", "\U0001F7E1": "YELLOW",
                      "\U0001F534": "RED", "⚪": "NO DATA"}


def build_pfc_pulse_trend(env, today):
    """The pulse over 30 days: per-lever days-on-target + the standing fix.

    pfc-pulse answers tonight; this answers lately. Thresholds, history, and
    remediation all come from pulse.py — one home for the pulse rules.
    Every count on this screen is GOOD days out of the window, so high is
    always good: an on-count headline over off-count rows meant every number
    had to be re-read for direction (AGENTS.md § "Metrics point one direction").
    Counts rather than a grid of status glyphs: a handful of ranked rows are
    legible across a room, 200-plus status marks are not.
    """
    from pulse import (VERDICT_MIN_CRITICAL_GREEN, chronic_misses, pulse_history,
                       pulse_levers, pulse_window_status)

    rows = read_ndjson("data/day-tracking.ndjson")
    hist = pulse_history(rows, 30)
    if hist is None:
        return {"window": 30, "from": "", "to": "", "levers": [], "chronic": None,
                "green_days": 0}

    n = len(hist["dates"])
    levers = []
    for lid in hist["order"]:
        s = hist["series"][lid]
        # `on` counts green days only; a day with no reading is neither on nor
        # off, so on + off can be < n.
        on = sum(1 for x in s["statuses"] if x == "🟢")
        levers.append({"id": lid, "label": s["label"], "on": on, "n": n,
                       "status": WINDOW_STATUS_WORD[pulse_window_status(s["statuses"])],
                       # target_plain, not target: the latter appends last night's
                       # distance-to-next-tier, which says nothing about a 30-day
                       # window and reads as if it did.
                       "target": _ascii(s.get("target_plain") or s["target"]),
                       "tier": s["tier"], "last": _ascii(s["last_disp"])})
    levers.sort(key=lambda lv: (lv["on"], lv["label"]))

    # Chronic = off on at least half the window, the same definition every other
    # pulse surface uses. Detected on off-days, reported as on-days so the
    # screen never mixes directions.
    worst = chronic_misses(hist, max_items=1)
    chronic = None
    if worst:
        off, lid, series, fix = worst[0]
        on = sum(1 for x in series["statuses"] if x == "🟢")
        chronic = {"label": series["label"], "on": on, "n": n,
                   "status": WINDOW_STATUS_WORD[pulse_window_status(series["statuses"])],
                   "fix": clip(_ascii(fix), 180)}

    # green_days: how often the setup for a great day was actually in place —
    # the same bar pulse_snapshot's verdict uses.
    by_date = {r["date"]: r for r in rows if r.get("date")}
    green_days = 0
    for d in hist["dates"]:
        lv = pulse_levers(by_date[d])
        status = {x[0]: x[6] for x in lv}
        crit_green = sum(1 for x in lv if x[1] == "CRITICAL" and x[6] == "🟢")
        if crit_green >= VERDICT_MIN_CRITICAL_GREEN and status.get("debt") != "🔴":
            green_days += 1

    return {"window": 30, "from": hist["dates"][0], "to": hist["dates"][-1],
            "levers": levers, "chronic": chronic, "green_days": green_days}


def build_pfc_front_of_mind(env, today):
    """Active grounding anchors — the small set of things to stay grounded in.

    The full view is poster-style while the list is small (<= 3 anchors): each
    anchor gets big centered type sized by its length, so one anchor fills the
    screen instead of leaving it 95% blank. Past 3 anchors it falls back to a
    list. The rotated copy lets small views lead with a different anchor each
    refresh so the whole set cycles into view.
    """
    anchors = [
        {"title": clip(g["title"], 90), "area": g.get("area") or ""}
        for g in sorted(
            (g for g in read_ndjson("data/grounding.ndjson") if g.get("status") == "active"),
            key=lambda g: g.get("created") or "",
        )
    ]
    for a in anchors:
        # A solo anchor sizes to its own length; a 2-3 poster stack caps at large.
        a["text_size"] = _text_size(a["title"]) if len(anchors) == 1 else "large"
        a["text_size_lg"] = _LG_BUMP[a["text_size"]]
    offset = (_minutes_since_epoch() // 15) % len(anchors) if anchors else 0
    return {
        "anchors": anchors,
        "anchors_rotated": anchors[offset:] + anchors[:offset],
        "count": len(anchors),
        "poster": len(anchors) <= 3,
    }


def _task_score(t, today):
    """pfc-pick-tasks scoring — keep in lockstep with that skill."""
    impact = {"high": 3, "medium": 2, "low": 1}.get(t.get("impact"), 1)
    urgency = {"high": 3, "medium": 2, "low": 1}.get(t.get("urgency"), 1)
    size = {"XS": 3, "S": 2, "M": 1, "L": 0, "XL": -1}.get(t.get("size"), 0)
    score = impact + urgency + size
    d = t.get("deadline")
    if d:
        days = (dt.date.fromisoformat(d) - dt.date.fromisoformat(today)).days
        score += 4 if days < 0 else (2 if days <= 7 else 0)
    c = t.get("created")
    if c and (dt.date.fromisoformat(today) - dt.date.fromisoformat(c)).days >= 14:
        score += 1
    return score


def _next_project_tasks(open_tasks, project_id, today, cap=4):
    """The next `cap` tasks for a project, ordered the way pfc-pick-tasks orders
    them: a sequenced project is an ordered curriculum (lowest sequence first);
    otherwise rank by the impact/urgency/size/deadline/stale score."""
    mine = [t for t in open_tasks if t.get("project") == project_id]
    sequenced = [t for t in mine if t.get("sequence") is not None]
    if sequenced:
        mine = sorted(sequenced, key=lambda t: t["sequence"])
    else:
        mine = sorted(mine, key=lambda t: -_task_score(t, today))
    return [{"title": clip(t["description"], 95)} for t in mine[:cap]]


# Max projects rendered on the pfc-projects screen. The registry allows many
# more; the e-ink panel does not. Overflow is reported, never silently dropped.
PROJECT_SCREEN_CAP = 6


def build_pfc_projects(env, today):
    """Active projects: percent + parts + deadline countdown + next open tasks."""
    open_tasks = [t for t in read_ndjson("6-tasks/_data/tasks.ndjson") if t.get("status") == "open"]
    projects = []
    for p in read_ndjson("5-projects/_data/projects.ndjson"):
        if not p.get("active"):
            continue
        total = p.get("total_parts") or 0
        done = p.get("completed_parts") or 0
        pct = round(100 * done / total) if total else 0
        deadline = p.get("deadline") or ""
        deadline_disp = ""
        if deadline:
            days_left = (dt.date.fromisoformat(deadline) - dt.date.fromisoformat(today)).days
            deadline_disp = (f"due {deadline} ({days_left}d)" if days_left >= 0
                             else f"due {deadline} ({-days_left}d late)")
        projects.append({
            "name": clip(p["name"], 60),
            "percent": pct,
            "parts": f"{done}/{total}" if total else "",
            "deadline_disp": deadline_disp,
            "tasks": _next_project_tasks(open_tasks, p["id"], today),
            "_deadline": deadline,
            "_urgency": p.get("urgency") or "low",
        })

    # There is no small cap on active projects (the validator's backstop is 12),
    # so this screen has to bound itself. `data-overflow-max-cols="1"` clips
    # silently, which reads as "that's all of them" — so cap here and say what
    # was cut.
    rank = {"high": 0, "medium": 1, "low": 2}
    projects.sort(key=lambda x: (
        x["_deadline"] == "",                 # dated projects first
        x["_deadline"],                       # soonest deadline first
        rank.get(x["_urgency"], 3),           # then urgency
        x["name"],
    ))
    total_active = len(projects)
    shown = projects[:PROJECT_SCREEN_CAP]
    for x in shown:
        x.pop("_deadline", None)
        x.pop("_urgency", None)
    hidden = total_active - len(shown)
    return {
        "projects": shown,
        "count": total_active,
        "hidden": hidden,
        "count_disp": f"{total_active} active" if not hidden else f"{len(shown)} of {total_active}",
    }


def build_pfc_trends(env, today):
    """Thirty days of day ratings with a 7-day rolling mean, plus 7-day tiles.

    Seven points is a week, not a direction — the rolling mean is what answers
    "is this getting better". Read-only retrospective; actions live on
    pfc-pulse, never here.
    """
    end = dt.date.fromisoformat(today)
    window = [(end - dt.timedelta(days=i)).isoformat() for i in range(29, -1, -1)]
    by_date = {r["date"]: r for r in read_ndjson("data/day-tracking.ndjson") if r.get("date")}

    days, mean = [], []
    ratings_seq = []
    for d in window:
        date_obj = dt.date.fromisoformat(d)
        label = f"{date_obj.strftime('%b')} {date_obj.day}"
        rating = by_date.get(d, {}).get("rating")
        days.append({"label": label, "rating": rating})
        ratings_seq.append(rating)
        recent = [r for r in ratings_seq[-7:] if r is not None]
        value = round(sum(recent) / len(recent), 1) if len(ratings_seq) >= 7 and recent else None
        # Bare values, positionally aligned with `days` — a per-point label here
        # doubles the payload past the webhook limit for zero rendered pixels.
        mean.append(value)

    week = window[-7:]
    in_week = [by_date[d] for d in week if d in by_date]
    sleeps = [r["health"]["sleep_hours"] for r in in_week
              if (r.get("health") or {}).get("sleep_hours") is not None]
    ratings = [r["rating"] for r in in_week if r.get("rating") is not None]

    exercised = _exercise_days()
    ex_week = sum(1 for d in week if d in exercised)
    ex_month = sum(1 for d in window if d in exercised)

    longest_gap, run = 0, 0
    for d in window:
        if d in exercised:
            run = 0
        else:
            run += 1
            longest_gap = max(longest_gap, run)
    current_gap = run

    # Rolling sleep debt. Prefer the computed value on the record (qqrt.py writes
    # it); fall back to a simple shortfall sum over the last 14 nights with data
    # so the tile still reads something before that automation is set up.
    debt = "-"
    for d in reversed(window):
        cumulative = ((by_date.get(d, {}).get("qqrt") or {}).get("sleep_debt") or {}).get("cumulative_hours")
        if cumulative is not None:
            debt = f"{cumulative:.1f}h"
            break
    else:
        deficit, seen = 0.0, 0
        for d in reversed(window):
            h = (by_date.get(d, {}).get("health") or {}).get("sleep_hours")
            if h is None:
                continue
            deficit += max(0.0, SLEEP_TARGET_HOURS - h)
            seen += 1
            if seen >= 14:
                break
        if seen:
            debt = f"{deficit:.1f}h"

    def avg(xs, fmt):
        return fmt.format(sum(xs) / len(xs)) if xs else "-"

    return {
        "days": days,
        "mean": mean,
        "avg_rating": avg(ratings, "{:.1f}"),
        "avg_sleep": avg(sleeps, "{:.1f}h"),
        "exercise": f"{ex_week}/7",
        "sleep_debt": debt,
        "exercise_line": f"{EXERCISE_LABEL.lower()} {ex_month}/30 - current gap {current_gap}d - longest gap {longest_gap}d",
    }


def _vision_items():
    """Active visions from 3-visions/*.md: title + the Statement blockquote."""
    out = []
    for p in sorted((REPO_ROOT / "3-visions").glob("*.md")):
        if p.name in ("README.md", "AGENTS.md", "CLAUDE.md") or p.name.startswith("_"):
            continue
        text = p.read_text()
        meta = {}
        if text.startswith("---"):
            for line in text.split("---")[1].splitlines():
                if ":" in line:
                    k, v = line.split(":", 1)
                    meta[k.strip()] = v.strip()
        if meta.get("status") != "active":
            continue
        title = next((l.lstrip("# ").strip() for l in text.splitlines() if l.startswith("# ")), p.stem)
        stmt = ""
        in_stmt = False
        for line in text.splitlines():
            if line.startswith("## "):
                in_stmt = line.strip() == "## Statement"
            elif in_stmt and line.startswith(">"):
                stmt = line.lstrip("> ").strip().strip('"')
                break
        if stmt.startswith("..."):        # untouched template placeholder
            stmt = ""
        out.append({"kind": "Vision", "title": title, "text": stmt,
                    "created": meta.get("created", "")})
    return out


_NUMBERED = re.compile(r"^\s*(\d+)\.\s+(.+?)\s*$")


def _values_items():
    """Your ranked values from 1-values/values.md.

    Numbered lines only (`1. Family`) — the starter file ships a long bulleted
    menu of suggestions, and putting an unranked menu on the wall would be
    showing you someone else's values. Rank yours as a numbered list and they
    appear here.
    """
    p = REPO_ROOT / "1-values" / "values.md"
    if not p.exists():
        return []
    out = []
    for line in p.read_text().splitlines():
        m = _NUMBERED.match(line)
        if m:
            out.append({"kind": "Value", "label": m.group(1), "text": m.group(2)})
    for it in out:
        it["label"] = f"#{it['label']} of {len(out)}"
    return out


def _area_statement_items():
    """The statement line from each 2-areas/<area>/statement.md.

    Takes the first quoted line or blockquote — write your statement as
    `> "..."` or `"..."` and it lands on the wall. Prose paragraphs are skipped
    on purpose: the starter files carry instructions, not statements.
    """
    out = []
    for p in sorted((REPO_ROOT / "2-areas").glob("*/statement.md")):
        for raw in p.read_text().splitlines():
            line = raw.strip().lstrip("> ").strip()
            if line.startswith('"') and len(line) > 2:
                out.append({"kind": "Area",
                            "label": p.parent.name.replace("-", " ").title(),
                            "text": line.strip('"')})
                break
    return out


def _question_items():
    """Life questions from 0-me/questions.md — numbered lines under
    '## Current Questions' when that heading exists, else numbered lines
    anywhere in the file. Bulleted examples in the starter file are skipped."""
    p = REPO_ROOT / "0-me" / "questions.md"
    if not p.exists():
        return []
    text = p.read_text()
    lines = text.splitlines()
    scoped = "## Current Questions" in text
    out, in_section = [], not scoped
    for line in lines:
        if line.startswith("## "):
            in_section = (not scoped) or line.strip() == "## Current Questions"
            continue
        if not in_section:
            continue
        m = _NUMBERED.match(line)
        if m:
            out.append({"kind": "Question", "label": f"Question {m.group(1)}",
                        "text": m.group(2)})
    return out


def _compass_vision_items():
    """Active visions, reshaped to the compass item contract (label/text)."""
    return [{"kind": "Vision", "label": v["title"], "text": v["text"]}
            for v in _vision_items() if v["text"]]


def build_pfc_compass(env, today):
    """One value, area statement, vision, or life question per refresh.

    Chosen commitments — near-static by nature, which is exactly why rotation
    carries them: a
    file re-read once a year is invisible; a different line every fifteen
    minutes is not.
    """
    items = (_values_items() + _area_statement_items() + _question_items()
             + _compass_vision_items())
    if not items:
        return {"kind": "", "label": "", "text": "Nothing to show.",
                "text_size": "large", "text_size_lg": "xlarge", "position": "0/0"}
    idx = (_minutes_since_epoch() // 15) % len(items)
    it = items[idx]
    text = clip(it["text"], 300)
    return {"kind": it["kind"], "label": it["label"],
            "text": text, "text_size": _text_size(text),
            "text_size_lg": _text_size_lg(text),
            "position": f"{idx + 1}/{len(items)}"}


# Highest-priority signal wins the label. A project that is both late and
# dormant reads "behind schedule" — the more actionable of the two.
SLIP_REASONS = [("A", "behind schedule"), ("B", "no parts done"), ("F", "dormant"),
                ("E", "carried in 2+1"), ("D", "high impact"), ("C", "stale")]


def build_pfc_back_on_track(env, today):
    """Every stated intention that has stopped moving, plus the smallest step back.

    One recovery surface across the intention layers — Current Focus (quarter),
    projects (months), habits (daily + monthly reps). Replaces the retired
    slipping screen: its task-level watchlist barely changed day to day and
    went invisible.
    Standalone tasks stay off this screen on purpose — task recovery is the
    2+1 / pick-tasks job; this screen covers the layers above it. Worst first
    everywhere. Every row carries the lowest-friction way back in (the focus
    landing anchor, the project's next task), because the re-entry step is the
    start trigger — a red row without one is just a wall of shame.
    """
    import revive_watchlist

    # Focus: red/yellow foundations + pursuits. Parked and retired are
    # deliberate states, not slippage; consuming has no "on track" to lose.
    focus = []
    for f in read_ndjson("4-focus/_data/focus.ndjson"):
        if f.get("status") not in ("red", "yellow") or f.get("tier") == "consuming":
            continue
        if f.get("parked") or f.get("retired_date"):
            continue
        focus.append({
            "title": clip(f.get("title") or "", 34),
            "status": STATUS_WORD[f["status"]],
            "tier": "Pursuit" if f.get("tier") == "pursuit" else "Foundation",
            "step": clip(_ascii(f.get("landing") or ""), 60),
            "_rank": 0 if f["status"] == "red" else 1,
        })
    focus.sort(key=lambda x: (x["_rank"], x["title"]))
    for x in focus:
        del x["_rank"]

    # Projects: the revive watchlist's project entries (same slip signals
    # /pfc-revive uses), days idle from task events, step = the next task.
    watch = revive_watchlist.compose_watchlist(REPO_ROOT, dt.date.fromisoformat(today))
    all_tasks = read_ndjson("6-tasks/_data/tasks.ndjson")
    open_tasks = [t for t in all_tasks if t.get("status") == "open"]
    projects_by_id = {p["id"]: p for p in read_ndjson("5-projects/_data/projects.ndjson")}
    last_event = {}
    for e in read_ndjson("6-tasks/_data/task_events.ndjson"):
        tid, ts = e.get("task_id"), (e.get("timestamp") or "")[:10]
        if tid and ts and ts > last_event.get(tid, ""):
            last_event[tid] = ts
    projects = []
    for it in watch:
        if it.item_type != "project":
            continue
        rec = projects_by_id.get(it.item_id, {})
        stamps = [last_event[t["id"]] for t in all_tasks
                  if t.get("project") == it.item_id and t["id"] in last_event]
        stamp = max(stamps) if stamps else (rec.get("started") or rec.get("created"))
        nxt = _next_project_tasks(open_tasks, it.item_id, today, cap=1)
        projects.append({
            "title": clip(rec.get("name") or it.item_id, 34),
            "days": _days_since(stamp, today),
            "reason": next((label for sig, label in SLIP_REASONS if sig in it.signals), "stale"),
            "step": clip(_ascii(nxt[0]["title"]), 60) if nxt else "pick its next task",
        })
    projects.sort(key=lambda x: -x["days"])

    # Daily habits, trailing 7 days against the ramped frequency. One miss on
    # a 7/wk habit is a wobble, not a derailment — flag only zero-for-the-week
    # or a gap of 2+ so the section stays signal, not a re-render of pfc-habits.
    week_start = (dt.date.fromisoformat(today) - dt.timedelta(days=6)).isoformat()
    week_counts = {}
    for h in read_ndjson("7-habits/_data/habits-daily.ndjson"):
        if h.get("completed") and week_start <= (h.get("date") or "") <= today:
            week_counts[h["habit_id"]] = week_counts.get(h["habit_id"], 0) + 1
    habits = []
    for h in daily_habits():
        done, target = week_counts.get(h["id"], 0), h.get("frequency", 7)
        if done == 0 or target - done >= 2:
            habits.append({"title": clip(_habit_title(h["id"]), 34),
                           "week": f"{done}/{target}", "_gap": target - done})
    habits.sort(key=lambda x: -x["_gap"])
    for x in habits:
        del x["_gap"]

    # Monthly habits behind pace (same pace math as build_pfc_habits).
    month = today[:7]
    today_date = dt.date.fromisoformat(today)
    days_in_month = (today_date.replace(day=28) + dt.timedelta(days=4)).replace(day=1) - dt.timedelta(days=1)
    month_frac = today_date.day / days_in_month.day
    mlogs = read_ndjson("7-habits/_data/habits-monthly.ndjson")
    monthly = []
    for h in monthly_habits():
        count = sum(1 for r in mlogs
                    if r.get("habit_id") == h["id"] and r.get("completed")
                    and (r.get("date") or "").startswith(month))
        target = h.get("frequency") or 1
        if count < target and count < target * month_frac:
            monthly.append({"title": clip(_habit_title(h["id"]), 34),
                            "count": f"{count}/{target}"})

    shown = {"focus": focus[:8], "projects": projects[:4],
             "habits": habits[:5], "monthly": monthly[:3]}
    overflow = (len(focus) + len(projects) + len(habits) + len(monthly)
                - sum(len(v) for v in shown.values()))
    total = len(focus) + len(projects) + len(habits) + len(monthly)
    return {**shown, "overflow": overflow, "total": total,
            "all_clear": total == 0}


def _read_calendar_cache():
    p = REPO_ROOT / "data" / "calendar-cache.json"
    return json.loads(p.read_text()) if p.exists() else None


def build_pfc_week(env, today):
    """Week at a Glance from the committed calendar cache.

    The cache is written by whatever fetches your calendar (the evening
    check-in's Calendar step) — this builder has no connector access of its own,
    by design: an HTTP endpoint that fans out to a third-party API per request
    is a bad idea for a wall screen.

    Filtering runs through config/trello_calendar_filters.yaml, shared with the
    Trello Week list so the two surfaces agree. The screen answers "what is
    happening this week that I would not already have guessed" — so PFC
    scaffolding, personal routines and known weekly patterns are hidden, while
    a ONE-OFF carrying a pattern's title still shows, because the exception is
    the whole point.

    Multi-day all-day events (trips, visitors in town) render on EVERY day they
    cover, not just their start date: an event you're inside of is the most
    relevant thing on a week grid, and Google's all-day `end.date` is
    exclusive."""
    from trello_render import calendar_event_excluded, load_calendar_filters

    tz = ZoneInfo(env.get("LOCAL_TZ", "America/Denver"))
    cache = _read_calendar_cache()
    if not cache:
        return {"days": [], "fetched": "", "stale": True}

    filters = load_calendar_filters()

    end = (dt.date.fromisoformat(today) + dt.timedelta(days=7)).isoformat()
    by_day = {}
    for ev in cache.get("events", []):
        if calendar_event_excluded(ev, filters):
            continue
        start = ev.get("start") or {}
        entry = {"title": clip(ev.get("summary") or "", 40)}
        if start.get("dateTime"):
            d = start["dateTime"][:10]
            t = dt.datetime.fromisoformat(start["dateTime"])
            entry["time"] = f"{t.hour % 12 or 12}:{t.minute:02d} {'AM' if t.hour < 12 else 'PM'}"
            days_covered = [d]
        elif start.get("date"):
            entry["time"] = "all day"
            # `end.date` is exclusive; a 01-05 → 01-07 event covers the 5th and 6th.
            first = dt.date.fromisoformat(start["date"][:10])
            stop = ((ev.get("end") or {}).get("date") or "")[:10]
            last = (dt.date.fromisoformat(stop) - dt.timedelta(days=1)) if stop else first
            if last < first:
                last = first
            days_covered = [(first + dt.timedelta(days=i)).isoformat()
                            for i in range((last - first).days + 1)]
        else:
            continue
        for d in days_covered:
            if today <= d < end:
                by_day.setdefault(d, []).append(dict(entry))

    # Sort within each day: all-day banners first, then timed events in clock
    # order. Spanning breaks the cache's own chronological order, so the day
    # lists have to be re-sorted here rather than inherited.
    def _slot(e):
        if e["time"] == "all day":
            return (0, 0, 0)
        clock, meridiem = e["time"].split(" ")
        hour, minute = (int(x) for x in clock.split(":"))
        hour = (hour % 12) + (12 if meridiem == "PM" else 0)
        return (1, hour, minute)

    for evs in by_day.values():
        evs.sort(key=_slot)

    # All 7 day slots, not just days with events — an empty day is real
    # information on a week screen. The full view's two-column grid slices this
    # itself with Liquid `limit: 4` / `offset: 4`; pre-sliced days_left /
    # days_right copies carried every event a second and third time and push
    # the payload past the 2 KB webhook ceiling once recurring commitments and
    # multi-day spans are included.
    days = []
    for i in range(7):
        d = (dt.date.fromisoformat(today) + dt.timedelta(days=i)).isoformat()
        days.append({
            "label": dt.date.fromisoformat(d).strftime("%a") + f" {int(d[5:7])}/{int(d[8:10])}",
            "events": by_day.get(d, []),
        })
    fetched_dt = dt.datetime.fromisoformat(cache["fetched_at"])
    age_h = (dt.datetime.now(tz) - fetched_dt).total_seconds() / 3600
    return {
        "days": days,
        "fetched": f"{int(fetched_dt.strftime('%m'))}/{int(fetched_dt.strftime('%d'))} "
                   + f"{fetched_dt.hour % 12 or 12}:{fetched_dt.minute:02d} {'AM' if fetched_dt.hour < 12 else 'PM'}",
        "stale": age_h > 26,
    }


def build_pfc_areas(env, today):
    """Life-wheel status per area, as a wall screen.

    Latest record in 2-areas/_data/life-wheel.ndjson: red/yellow areas lead with
    their notes (the why), green areas hold a compact list. Both wheel shapes
    work — colour ratings (`ratings`) and numeric 1-10 scores (`scores`), which
    are bucketed by the same rule the Trello render uses. The rated date is
    always shown; past ~40 days the wheel itself is the stale thing worth
    knowing.
    """
    from trello_render import _lifewheel_color

    rows = read_ndjson("2-areas/_data/life-wheel.ndjson")
    if not rows:
        return {"attention": [], "holding": [], "rated": "", "stale": False,
                "reds": 0, "yellows": 0, "greens": 0}
    latest = rows[-1]
    raw = latest.get("ratings") or latest.get("scores") or {}
    notes = latest.get("notes") or {}
    colors = {area: _lifewheel_color(v) for area, v in raw.items()}

    order = {"red": 0, "yellow": 1, "green": 2}
    attention, holding = [], []
    for area, color in sorted(colors.items(), key=lambda kv: (order.get(kv[1], 3), kv[0])):
        entry = {"title": area.replace("-", " ").title(),
                 "mark": STATUS_WORD.get(color, "NO DATA"),
                 "note": clip(notes.get(area) or "", 110)}
        (attention if color in ("red", "yellow") else holding).append(entry)

    rated = latest.get("date") or ""
    stale = bool(rated) and _days_since(rated, today) > 40
    return {
        "attention": attention,
        "holding": holding,
        "rated": rated,
        "stale": stale,
        "reds": sum(1 for c in colors.values() if c == "red"),
        "yellows": sum(1 for c in colors.values() if c == "yellow"),
        "greens": sum(1 for c in colors.values() if c == "green"),
    }


FOCUS_MARK = STATUS_WORD
FOCUS_PARKED_MARK = "PARKED"
FOCUS_LETTER = {"high": "A", "medium": "B", "low": "C"}
FOCUS_RED_FIRST = {"red": 0, "yellow": 1, "green": 2}


def build_pfc_focus(env, today):
    """Current Focus: the capped, traffic-lit quarterly set (4-focus).

    Ordering and the two-letter impact/urgency code mirror `render_focus` in
    trello_render.py on purpose — the same set on two surfaces must not read in
    two different orders. AA (high impact, high urgency) first, red-first as the
    tiebreak within a code.
    """
    live = [f for f in read_ndjson("4-focus/_data/focus.ndjson") if not f.get("retired_date")]

    def code(f):
        return (FOCUS_LETTER.get(f.get("impact"), "C")
                + FOCUS_LETTER.get(f.get("urgency"), "C"))

    def entries(tier, with_landing=False):
        tier_focuses = sorted(
            (f for f in live if f.get("tier") == tier),
            key=lambda f: (code(f), FOCUS_RED_FIRST.get(f.get("status"), 9)),
        )
        out = []
        for f in tier_focuses:
            mark = (FOCUS_PARKED_MARK if f.get("parked")
                    else FOCUS_MARK.get(f.get("status"), STATUS_WORD["green"]))
            e = {"title": clip(f["title"], 60), "mark": mark, "code": code(f)}
            if with_landing:
                e["landing"] = clip(f.get("landing") or "", 150)
            out.append(e)
        return out

    return {
        "foundations": entries("foundation"),
        "pursuits": entries("pursuit", with_landing=True),
        "consuming": entries("consuming"),
        "quarter": next((f.get("quarter") for f in live if f.get("quarter")), ""),
    }


