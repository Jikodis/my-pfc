#!/usr/bin/env python3
"""
TRMNL payload builders + the webhook transport.

    python3 automations/scripts/trmnl_push.py <plugin> [--dry-run] [--local] [--out PATH] [--force]

    <plugin>    Folder name under trmnl/ (e.g. pfc-today). Must have a builder
                registered in BUILDERS below.
    --dry-run   Print the payload and its byte size. No network call.
    --local     Write the payload into trmnl/<plugin>/.trmnlp.yml under the
                generated marker so `trmnlp serve` previews against real data.
                No network call.
    --out PATH  Write the payload as bare JSON to PATH (the polling transport's
                shape). No network call.
    --force     Skip the local rate-limit guard.

BUILDERS below is the one registry of screens. Both transports read it:
`trmnl_serve.py` calls a builder per HTTP request (polling, the default), and a
bare invocation here POSTs the result as a webhook body. The screens mirror the
web home page band for band; those builders live in `trmnl_home.py` and read
`home_data.build_home`, the same call the page makes. This file keeps the shared
helpers, the two screens with no page band of their own (Front of mind, Week),
and the pulse builders that `home_data` folds into its Body first band.

Webhook UUID comes from .env as TRMNL_WEBHOOK_<PLUGIN_SLUG_UPPER> — the plugin
folder `pfc-today` reads TRMNL_WEBHOOK_PFC_TODAY.

Why the guards: TRMNL rate-limits webhook pushes to 12 requests/hour at 2 KB per
request on a standard account (30/hour at 5 KB on TRMNL+). Blowing the limit
returns 429 and the screen goes stale, so this script refuses to push more often
than MIN_PUSH_INTERVAL_SECONDS and refuses to send an oversized payload at all.
See docs/trmnl-plugins.md.
"""

import argparse
import datetime as dt
import json
import os
import sys
import urllib.error
import urllib.request
from pathlib import Path
from zoneinfo import ZoneInfo

SCRIPT_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPT_DIR))

REPO_ROOT = SCRIPT_DIR.parents[1]
TRMNL_DIR = REPO_ROOT / "trmnl"

WEBHOOK_BASE = "https://trmnl.com/api/custom_plugins"
TIMEOUT_SECONDS = 15

# Standard account: 12 req/hr. One push per 5 minutes stays well inside it.
MIN_PUSH_INTERVAL_SECONDS = 300
DEFAULT_PAYLOAD_LIMIT_BYTES = 2048

GENERATED_MARKER = "# --- generated by trmnl_push.py --local (do not hand-edit below) ---"

# The exercise / movement habit the pulse builder reports on. One setting for every
# surface: change it in pfc_writes.py, which the web page's Body first band reads too.
from pfc_writes import EXERCISE_HABIT_ID, EXERCISE_LABEL  # noqa: E402,F401



# ── env ───────────────────────────────────────────────────────────────────────


def load_env():
    """Load .env into a dict, then let real environment variables win."""
    env = {}
    env_path = REPO_ROOT / ".env"
    if env_path.exists():
        for line in env_path.read_text().splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            v = v.strip()
            # Values may be quoted so bash `source` survives shell metacharacters
            # (an unquoted & in a value would otherwise break the bin/ scripts).
            env[k.strip()] = v[1:-1] if len(v) >= 2 and v[0] == v[-1] and v[0] in "'\"" else v
    env.update({k: v for k, v in os.environ.items() if v})
    return env


def today_local(env) -> str:
    tz = ZoneInfo(env.get("LOCAL_TZ", "America/Denver"))
    return dt.datetime.now(tz).strftime("%Y-%m-%d")


# ── repo readers ──────────────────────────────────────────────────────────────


def read_ndjson(rel_path):
    p = REPO_ROOT / rel_path
    if not p.exists():
        return []
    out = []
    for line in p.read_text().splitlines():
        line = line.strip()
        if line:
            out.append(json.loads(line))
    return out


def daily_habits():
    """Daily habit definitions from config/habit_schema.yaml, active only."""
    from trello_render import _load_habit_schema

    return [h for h in _load_habit_schema()["daily"] if h.get("active", True)]


def monthly_habits():
    """Monthly habit definitions from config/habit_schema.yaml, active only."""
    from trello_render import _load_habit_schema

    return [h for h in _load_habit_schema()["monthly"] if h.get("active", True)]


def clip(text, limit):
    text = (text or "").strip()
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def _minutes_since_epoch():
    return int(dt.datetime.now(dt.timezone.utc).timestamp() // 60)


def _exercise_days():
    """Dates the exercise habit was done, from either source that records it:
    a completed habit log, or `morning_movement: true` on a day-tracking row."""
    dates = {r["date"] for r in read_ndjson("7-habits/_data/habits-daily.ndjson")
             if r.get("habit_id") == EXERCISE_HABIT_ID and r.get("completed") and r.get("date")}
    dates |= {r["date"] for r in read_ndjson("data/day-tracking.ndjson")
              if r.get("morning_movement") and r.get("date")}
    return dates


def _ascii(text):
    """Targets carry ≥ / ≤ glyphs and fix strings carry em dashes; e-ink renders
    those unreliably (same class of failure as emoji). Transliterate rather than
    dropping the comparison."""
    return ((text or "").replace("≥", ">=").replace("≤", "<=")
            .replace("—", "-").replace("–", "-").replace("×", "x")
            .replace("→", "->").replace("·", "-"))


# E-ink status marks — screens have no emoji font, so a status becomes the
# colour spelled out in caps. Punctuation marks ([!] / [~] / [ ]) need a legend,
# and a legend that isn't printed on the screen is a legend the viewer doesn't
# have. A word is its own legend. ONE vocabulary across every screen —
# see AGENTS.md § "Metrics point one direction". STATUS_WORD is keyed by colour
# name, EINK_MARK by the pulse machinery's emoji; they must never diverge.
STATUS_WORD = {"green": "GREEN", "yellow": "YELLOW", "red": "RED"}
EINK_MARK = {"🟢": STATUS_WORD["green"], "🟡": STATUS_WORD["yellow"],
             "🔴": STATUS_WORD["red"], "⚪": "NO DATA"}


def _text_size(text):
    """Typography tier picked in Python so Liquid stays logic-free."""
    if len(text) <= 24:
        return "giga"
    if len(text) <= 120:
        return "large"
    return "base"


# One tier up for the TRMNL X's larger render (the `lg:` breakpoint). `giga` is
# the ceiling — there is no readable step above it on e-ink.
_LG_BUMP = {"giga": "giga", "large": "xlarge", "base": "large"}


def _text_size_lg(text):
    return _LG_BUMP[_text_size(text)]


# ── payload builders ──────────────────────────────────────────────────────────
#
# A builder takes (env, today) and returns the dict that becomes the plugin's
# merge variables. Keep every builder under the payload byte limit — pre-digest
# here rather than doing the work in Liquid. Nothing nested more than two
# levels deep.


def build_pfc_pulse(env, today):
    """Daily Pulse: levers vs target, the verdict, and tonight's one move.

    Thresholds, verdict, and move all come from pulse.pulse_snapshot — if tiering
    or targets change, they change there (or in `health.pulse` in
    config/automation_config.yaml), in one place.
    """
    from pulse import pulse_snapshot

    snap = pulse_snapshot(read_ndjson("data/day-tracking.ndjson"))
    exercised = today in _exercise_days()
    if snap is None:
        return {"date": today, "levers": [], "verdict_mark": "NO DATA",
                "verdict": "No day-tracking data yet.", "move": "",
                "exercise_label": EXERCISE_LABEL, "exercise_done": exercised,
                "exercise_text": "done" if exercised else "not yet"}

    status_rank = {"🔴": 0, "🟡": 1, "🟢": 2, "⚪": 3}
    # _ascii on value/target: they carry >= / <= glyphs that e-ink renders
    # unreliably — the same treatment build_pfc_pulse_trend gives them.
    # Red first, then yellow, then green — worst at the top so the thing to fix
    # is the thing you read first. Tier only breaks ties within a colour.
    levers = [
        {"label": label, "value": _ascii(disp), "target": _ascii(target), "tier": tier,
         "mark": EINK_MARK[status]}
        for (lid, tier, rank, label, disp, target, status)
        in sorted(snap["levers"], key=lambda lv: (status_rank[lv[6]], lv[2]))
    ]
    return {
        "date": snap["date"],
        "levers": levers,
        "verdict_mark": EINK_MARK[snap["verdict"]["status"]],
        "verdict": _ascii(snap["verdict"]["text"]),
        "move": clip(_ascii(snap["move"]), 140),
        # Today's action, independent of `snap` — which may still show last
        # night's sleep during the pre-noon gap.
        "exercise_label": EXERCISE_LABEL,
        "exercise_done": exercised,
        "exercise_text": "done" if exercised else "not yet",
    }


# Window rollups spell the colour out — same one-vocabulary rule as EINK_MARK.
WINDOW_STATUS_WORD = {"\U0001F7E2": "GREEN", "\U0001F7E1": "YELLOW",
                      "\U0001F534": "RED", "⚪": "NO DATA"}


def build_pfc_pulse_trend(env, today):
    """The pulse over 30 days: per-lever days-on-target + the standing fix.

    pfc-pulse answers tonight; this answers lately. Thresholds, history, and
    remediation all come from pulse.py — one home for the pulse rules.
    Every count on this screen is GOOD days out of the window, so high is
    always good: an on-count headline over off-count rows meant every number
    had to be re-read for direction (AGENTS.md § "Metrics point one direction").
    Counts rather than a grid of status glyphs: a handful of ranked rows are
    legible across a room, 200-plus status marks are not.
    """
    from pulse import (VERDICT_MIN_CRITICAL_GREEN, chronic_misses, pulse_history,
                       pulse_levers, pulse_window_status)

    rows = read_ndjson("data/day-tracking.ndjson")
    hist = pulse_history(rows, 30)
    if hist is None:
        return {"window": 30, "from": "", "to": "", "levers": [], "chronic": None,
                "green_days": 0}

    n = len(hist["dates"])
    levers = []
    for lid in hist["order"]:
        s = hist["series"][lid]
        # `on` counts green days only; a day with no reading is neither on nor
        # off, so on + off can be < n.
        on = sum(1 for x in s["statuses"] if x == "🟢")
        levers.append({"id": lid, "label": s["label"], "on": on, "n": n,
                       "status": WINDOW_STATUS_WORD[pulse_window_status(s["statuses"])],
                       # target_plain, not target: the latter appends last night's
                       # distance-to-next-tier, which says nothing about a 30-day
                       # window and reads as if it did.
                       "target": _ascii(s.get("target_plain") or s["target"]),
                       "tier": s["tier"], "last": _ascii(s["last_disp"])})
    levers.sort(key=lambda lv: (lv["on"], lv["label"]))

    # Chronic = off on at least half the window, the same definition every other
    # pulse surface uses. Detected on off-days, reported as on-days so the
    # screen never mixes directions.
    worst = chronic_misses(hist, max_items=1)
    chronic = None
    if worst:
        off, lid, series, fix = worst[0]
        on = sum(1 for x in series["statuses"] if x == "🟢")
        chronic = {"label": series["label"], "on": on, "n": n,
                   "status": WINDOW_STATUS_WORD[pulse_window_status(series["statuses"])],
                   "fix": clip(_ascii(fix), 180)}

    # green_days: how often the setup for a great day was actually in place —
    # the same bar pulse_snapshot's verdict uses.
    by_date = {r["date"]: r for r in rows if r.get("date")}
    green_days = 0
    for d in hist["dates"]:
        lv = pulse_levers(by_date[d])
        status = {x[0]: x[6] for x in lv}
        crit_green = sum(1 for x in lv if x[1] == "CRITICAL" and x[6] == "🟢")
        if crit_green >= VERDICT_MIN_CRITICAL_GREEN and status.get("debt") != "🔴":
            green_days += 1

    return {"window": 30, "from": hist["dates"][0], "to": hist["dates"][-1],
            "levers": levers, "chronic": chronic, "green_days": green_days}



def build_pfc_front_of_mind(env, today):
    """Active grounding anchors — the small set of things to stay grounded in.

    The full view is poster-style while the list is small (<= 3 anchors): each
    anchor gets big centered type sized by its length, so one anchor fills the
    screen instead of leaving it 95% blank. Past 3 anchors it falls back to a
    list. The rotated copy lets small views lead with a different anchor each
    refresh so the whole set cycles into view.
    """
    anchors = [
        {"title": clip(g["title"], 90), "area": g.get("area") or ""}
        for g in sorted(
            (g for g in read_ndjson("data/grounding.ndjson") if g.get("status") == "active"),
            key=lambda g: g.get("created") or "",
        )
    ]
    for a in anchors:
        # A solo anchor sizes to its own length; a stack of 2 is large, 3 is base
        # (large clips at 800x480).
        a["text_size"] = _text_size(a["title"]) if len(anchors) == 1 else "large" if len(anchors) == 2 else "base"
        a["text_size_lg"] = _LG_BUMP[a["text_size"]]
    offset = (_minutes_since_epoch() // 15) % len(anchors) if anchors else 0
    return {
        "title": "Front of mind",
        "horizon": "Always: the anchors to keep in view.",
        "anchors": anchors,
        "anchors_rotated": anchors[offset:] + anchors[:offset],
        "count": len(anchors),
        "poster": len(anchors) <= 3,
    }


def _read_calendar_cache():
    p = REPO_ROOT / "data" / "calendar-cache.json"
    return json.loads(p.read_text()) if p.exists() else None


WEEK_HORIZON = "The next seven days, from the calendar."
WEEK_DAY_EVENTS = 14


def _parse_fetched_at(raw, tz):
    """The cache stamp. BSD `date` has no `%:z`, so a stamp written on macOS can end
    in a literal `:z` (`2025-01-06T08:15:20:z`); read the clock part as local time
    rather than crash the whole Week screen over its footer."""
    try:
        parsed = dt.datetime.fromisoformat(raw)
    except (TypeError, ValueError):
        try:
            parsed = dt.datetime.fromisoformat(str(raw)[:19])
        except ValueError:
            return dt.datetime.now(tz) - dt.timedelta(days=30)
    return parsed if parsed.tzinfo else parsed.replace(tzinfo=tz)


def build_pfc_week(env, today):
    """Week at a Glance from the committed calendar cache.

    The cache is written by whatever fetches your calendar (the daily sync job,
    or /pfc-render-trello's calendar step) — this builder has no connector access of its own,
    by design: an HTTP endpoint that fans out to a third-party API per request
    is a bad idea for a wall screen.

    Filtering runs through config/trello_calendar_filters.yaml, shared with the
    Trello Week list so the two surfaces agree. The screen answers "what is
    happening this week that I would not already have guessed" — so PFC
    scaffolding, personal routines and known weekly patterns are hidden, while
    a ONE-OFF carrying a pattern's title still shows, because the exception is
    the whole point.

    Multi-day all-day events (trips, visitors in town) render on EVERY day they
    cover, not just their start date: an event you're inside of is the most
    relevant thing on a week grid, and Google's all-day `end.date` is
    exclusive."""
    from trello_render import calendar_event_excluded, load_calendar_filters

    tz = ZoneInfo(env.get("LOCAL_TZ", "America/Denver"))
    cache = _read_calendar_cache()
    if not cache:
        return {"title": "Week", "horizon": WEEK_HORIZON, "days": [], "fetched": "", "stale": True}

    filters = load_calendar_filters()

    end = (dt.date.fromisoformat(today) + dt.timedelta(days=7)).isoformat()
    by_day = {}
    for ev in cache.get("events", []):
        if calendar_event_excluded(ev, filters):
            continue
        start = ev.get("start") or {}
        # ASCII only: an emoji in a title draws as an empty box on e-ink.
        entry = {"title": clip(_ascii(ev.get("summary") or "").encode("ascii", "ignore").decode().strip(), 32)}
        if start.get("dateTime"):
            d = start["dateTime"][:10]
            t = dt.datetime.fromisoformat(start["dateTime"])
            entry["time"] = f"{t.hour % 12 or 12}:{t.minute:02d} {'AM' if t.hour < 12 else 'PM'}"
            days_covered = [d]
        elif start.get("date"):
            entry["time"] = "all day"
            # `end.date` is exclusive; a 01-05 → 01-07 event covers the 5th and 6th.
            first = dt.date.fromisoformat(start["date"][:10])
            stop = ((ev.get("end") or {}).get("date") or "")[:10]
            last = (dt.date.fromisoformat(stop) - dt.timedelta(days=1)) if stop else first
            if last < first:
                last = first
            days_covered = [(first + dt.timedelta(days=i)).isoformat()
                            for i in range((last - first).days + 1)]
        else:
            continue
        for d in days_covered:
            if today <= d < end:
                by_day.setdefault(d, []).append(dict(entry))

    # Sort within each day: all-day banners first, then timed events in clock
    # order. Spanning breaks the cache's own chronological order, so the day
    # lists have to be re-sorted here rather than inherited.
    def _slot(e):
        if e["time"] == "all day":
            return (0, 0, 0)
        clock, meridiem = e["time"].split(" ")
        hour, minute = (int(x) for x in clock.split(":"))
        hour = (hour % 12) + (12 if meridiem == "PM" else 0)
        return (1, hour, minute)

    for evs in by_day.values():
        evs.sort(key=_slot)

    # All 7 day slots, not just days with events — an empty day is real
    # information on a week screen. The full view flows the days across its
    # columns itself; pre-sliced per-column copies would carry every event a
    # second time and push the payload past the 2 KB webhook ceiling.
    days = []
    for i in range(7):
        d = (dt.date.fromisoformat(today) + dt.timedelta(days=i)).isoformat()
        days.append({
            "label": dt.date.fromisoformat(d).strftime("%a") + f" {int(d[5:7])}/{int(d[8:10])}",
            # WEEK_DAY_EVENTS is a runaway guard; the full view flows every day across columns.
            "events": by_day.get(d, [])[:WEEK_DAY_EVENTS],
            "more": max(len(by_day.get(d, [])) - WEEK_DAY_EVENTS, 0),
        })
    fetched_dt = _parse_fetched_at(cache.get("fetched_at"), tz)
    age_h = (dt.datetime.now(tz) - fetched_dt).total_seconds() / 3600
    return {
        "title": "Week",
        "horizon": WEEK_HORIZON,
        "days": days,
        "fetched": f"{int(fetched_dt.strftime('%m'))}/{int(fetched_dt.strftime('%d'))} "
                   + f"{fetched_dt.hour % 12 or 12}:{fetched_dt.minute:02d} {'AM' if fetched_dt.hour < 12 else 'PM'}",
        "stale": age_h > 26,
    }


