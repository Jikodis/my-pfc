# ── push ──────────────────────────────────────────────────────────────────────


def env_key(plugin):
    return "TRMNL_WEBHOOK_" + plugin.replace("-", "_").upper()


def stamp_path(plugin):
    return REPO_ROOT / "data" / f".trmnl-last-push-{plugin}"


def rate_limited(plugin):
    """Return seconds still to wait, or 0 when a push is allowed."""
    p = stamp_path(plugin)
    if not p.exists():
        return 0
    elapsed = dt.datetime.now().timestamp() - p.stat().st_mtime
    remaining = MIN_PUSH_INTERVAL_SECONDS - elapsed
    return int(remaining) if remaining > 0 else 0


def post_payload(uuid, payload):
    body = json.dumps({"merge_variables": payload}).encode()
    req = urllib.request.Request(
        f"{WEBHOOK_BASE}/{uuid}",
        data=body,
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(req, timeout=TIMEOUT_SECONDS) as resp:
        return resp.status, resp.read().decode()


def write_local_fixture(plugin, payload):
    """Rewrite the generated block of trmnl/<plugin>/.trmnlp.yml with the payload.

    JSON is valid YAML, so the payload is emitted as a flow mapping — no YAML
    library needed. Everything above the marker is preserved verbatim.
    """
    path = TRMNL_DIR / plugin / ".trmnlp.yml"
    if not path.exists():
        raise SystemExit(f"No .trmnlp.yml at {path}")
    head = path.read_text().split(GENERATED_MARKER)[0].rstrip() + "\n"
    block = json.dumps(payload, indent=2)
    path.write_text(f"{head}\n{GENERATED_MARKER}\nvariables:\n  " + block.replace("\n", "\n  ") + "\n")
    return path


def main(argv):
    parser = argparse.ArgumentParser(description="Build and push a TRMNL plugin payload.")
    parser.add_argument("plugin", help="plugin folder name under trmnl/")
    parser.add_argument("--dry-run", action="store_true", help="print the payload, do not send")
    parser.add_argument("--local", action="store_true", help="write the payload into .trmnlp.yml for trmnlp serve")
    parser.add_argument("--out", metavar="PATH", help="write the payload JSON to PATH (the polling shape); no network call")
    parser.add_argument("--force", action="store_true", help="skip the rate-limit guard")
    args = parser.parse_args(argv)

    builder = BUILDERS.get(args.plugin)
    if builder is None:
        print(
            f"No payload builder registered for '{args.plugin}'. "
            f"Known: {', '.join(sorted(BUILDERS))}. Add one in {Path(__file__).name}.",
            file=sys.stderr,
        )
        return 1

    env = load_env()
    payload = builder(env, today_local(env))
    encoded = json.dumps({"merge_variables": payload})
    size = len(encoded.encode())
    limit = int(env.get("TRMNL_PAYLOAD_LIMIT", DEFAULT_PAYLOAD_LIMIT_BYTES))

    if args.out:
        # Polling transport: TRMNL fetches this file, so it is served bare
        # rather than wrapped in {"merge_variables": ...} the way a webhook
        # body is.
        out = Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(payload, indent=2) + "\n")
        print(f"wrote {out} ({len(json.dumps(payload).encode())} bytes)", file=sys.stderr)
        return 0

    if args.dry_run or args.local:
        print(json.dumps(payload, indent=2))
        print(f"\npayload: {size} bytes (limit {limit})", file=sys.stderr)
        if size > limit:
            print("OVER LIMIT — trim the builder before pushing.", file=sys.stderr)
        if args.local:
            print(f"wrote {write_local_fixture(args.plugin, payload)}", file=sys.stderr)
        return 0

    if size > limit:
        print(
            f"Payload is {size} bytes, over the {limit}-byte TRMNL webhook limit. "
            f"Trim the builder for '{args.plugin}' — do not raise the limit unless the "
            f"account is on TRMNL+ (5 KB).",
            file=sys.stderr,
        )
        return 1

    uuid = env.get(env_key(args.plugin))
    if not uuid:
        print(
            f"Missing {env_key(args.plugin)} in .env — copy the plugin's webhook UUID "
            f"from its TRMNL settings page. See .env.example.",
            file=sys.stderr,
        )
        return 1

    wait = 0 if args.force else rate_limited(args.plugin)
    if wait:
        print(
            f"Last push was under {MIN_PUSH_INTERVAL_SECONDS}s ago; {wait}s to go. "
            f"TRMNL allows 12 pushes/hour. Re-run with --force to override.",
            file=sys.stderr,
        )
        return 1

    try:
        status, body = post_payload(uuid, payload)
    except urllib.error.HTTPError as e:
        detail = e.read().decode(errors="replace")[:300]
        print(f"TRMNL returned HTTP {e.code}: {detail}", file=sys.stderr)
        return 1
    except urllib.error.URLError as e:
        print(f"Could not reach TRMNL: {e.reason}", file=sys.stderr)
        return 1

    stamp_path(args.plugin).write_text(dt.datetime.now().isoformat())
    print(f"pushed {args.plugin}: HTTP {status} ({size} bytes) {body[:200]}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
