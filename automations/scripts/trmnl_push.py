#!/usr/bin/env python3
"""
TRMNL payload builders + the webhook transport.

    python3 automations/scripts/trmnl_push.py <plugin> [--dry-run] [--local] [--out PATH] [--force]

    <plugin>    Folder name under trmnl/ (e.g. pfc-today). Must have a builder
                registered in BUILDERS below.
    --dry-run   Print the payload and its byte size. No network call.
    --local     Write the payload into trmnl/<plugin>/.trmnlp.yml under the
                generated marker so `trmnlp serve` previews against real data.
                No network call.
    --out PATH  Write the payload as bare JSON to PATH (the polling transport's
                shape). No network call.
    --force     Skip the local rate-limit guard.

This file holds every payload builder. Both transports read the same BUILDERS
registry: `trmnl_serve.py` calls a builder per HTTP request (polling, the
default), and a bare invocation here POSTs the result as a webhook body.

Webhook UUID comes from .env as TRMNL_WEBHOOK_<PLUGIN_SLUG_UPPER> — the plugin
folder `pfc-today` reads TRMNL_WEBHOOK_PFC_TODAY.

Why the guards: TRMNL rate-limits webhook pushes to 12 requests/hour at 2 KB per
request on a standard account (30/hour at 5 KB on TRMNL+). Blowing the limit
returns 429 and the screen goes stale, so this script refuses to push more often
than MIN_PUSH_INTERVAL_SECONDS and refuses to send an oversized payload at all.
See docs/trmnl-plugins.md.
"""

